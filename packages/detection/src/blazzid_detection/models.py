"""Data models and contracts for gameplay event detection."""

from __future__ import annotations

from enum import Enum
from pathlib import Path
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field

from blazzid_core.contracts.events import GameplayEventCandidate


class DetectorType(str, Enum):
    """Categorized detection sub-engines."""

    VISUAL_ACTIVITY = "VISUAL_ACTIVITY"
    VISUAL_BURST = "VISUAL_BURST"
    SCENE_TRANSITION = "SCENE_TRANSITION"
    SUSTAINED_COMBAT = "SUSTAINED_COMBAT"


class FrameFeatureRecord(BaseModel):
    """Timestamped visual features extracted from a single video frame.

    All metrics are bounded and normalized with well-defined units:
    - mean_luminance: [0.0, 255.0] average pixel intensity in grayscale.
    - std_luminance: [0.0, 128.0] standard deviation of grayscale luminance.
    - histogram: 16-bin L1-normalized grayscale distribution (sums to 1.0).
    - frame_difference: [0.0, 1.0] normalized mean absolute difference relative to prior frame.
    - histogram_distance: [0.0, 1.0] Bhattacharyya distance relative to prior histogram.
    - edge_density: [0.0, 1.0] spatial Sobel gradient density.
    """

    model_config = ConfigDict(frozen=True)

    frame_index: int = Field(..., ge=0, description="Sequential sampling index.")
    timestamp_seconds: float = Field(
        ..., ge=0.0, description="Source presentation timestamp in seconds."
    )
    file_path: Optional[Path] = Field(
        default=None, description="Filesystem path to source frame image."
    )
    width: int = Field(..., gt=0, description="Frame width in pixels.")
    height: int = Field(..., gt=0, description="Frame height in pixels.")
    mean_luminance: float = Field(
        default=0.0, ge=0.0, le=255.0, description="Average grayscale intensity."
    )
    std_luminance: float = Field(
        default=0.0, ge=0.0, description="Standard deviation of grayscale intensity."
    )
    histogram: list[float] = Field(
        default_factory=list, description="Normalized 16-bin luminance histogram."
    )
    frame_difference: float = Field(
        default=0.0, ge=0.0, le=1.0, description="Normalized pixel delta from prior frame."
    )
    histogram_distance: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0,
        description="Bhattacharyya distance from prior frame histogram.",
    )
    edge_density: float = Field(
        default=0.0, ge=0.0, le=1.0, description="Normalized edge gradient magnitude."
    )
    is_valid: bool = Field(
        default=True, description="Whether frame was decoded and analyzed successfully."
    )
    error_message: Optional[str] = Field(
        default=None, description="Diagnostic error if frame decode failed."
    )


class RawEventTrigger(BaseModel):
    """An un-merged intermediate event hypothesis generated by an individual detector."""

    model_config = ConfigDict(frozen=True)

    detector_type: DetectorType = Field(
        ..., description="Detector sub-engine that triggered the event."
    )
    start_seconds: float = Field(..., ge=0.0, description="Trigger interval start timestamp.")
    end_seconds: float = Field(..., ge=0.0, description="Trigger interval end timestamp.")
    peak_seconds: float = Field(..., ge=0.0, description="Timestamp of maximum signal intensity.")
    peak_intensity: float = Field(..., ge=0.0, description="Peak metric value at climax.")
    raw_score: float = Field(..., ge=0.0, description="Detector-specific raw signal magnitude.")
    confidence: float = Field(
        ..., ge=0.0, le=1.0, description="Initial heuristic confidence [0.0, 1.0]."
    )
    supporting_features: dict[str, Any] = Field(
        default_factory=dict, description="Raw feature measurements supporting the trigger."
    )
    frame_indices: list[int] = Field(
        default_factory=list, description="Frame indices spanning this trigger episode."
    )


class DetectionDiagnostics(BaseModel):
    """Audit and telemetry statistics for a detection execution run."""

    model_config = ConfigDict(frozen=True)

    total_frames_analyzed: int = Field(..., ge=0, description="Total frame count processed.")
    valid_frames_count: int = Field(
        ..., ge=0, description="Successfully extracted and decoded frames."
    )
    corrupt_or_missing_frames_count: int = Field(
        ..., ge=0, description="Unreadable or missing frames."
    )
    source_duration_seconds: float = Field(
        ..., ge=0.0, description="Total source video length in seconds."
    )
    temporal_coverage_ratio: float = Field(
        ..., ge=0.0, le=1.0, description="Fraction of source timeline covered by valid frames."
    )
    mean_sampling_interval_seconds: float = Field(
        ..., ge=0.0, description="Average time between analyzed frames."
    )
    events_detected_by_type: dict[str, int] = Field(
        default_factory=dict, description="Histogram of detected events by event type."
    )
    execution_elapsed_seconds: float = Field(
        ..., ge=0.0, description="Total wall-clock runtime for event detection."
    )


class DetectionResult(BaseModel):
    """Complete structured output from gameplay event detection."""

    model_config = ConfigDict(frozen=True)

    candidates: list[GameplayEventCandidate] = Field(
        ..., description="Timestamped, explainable gameplay event candidates."
    )
    diagnostics: DetectionDiagnostics = Field(
        ..., description="Execution telemetry and audit metrics."
    )
    features: list[FrameFeatureRecord] = Field(
        default_factory=list, description="Frame-by-frame visual feature timeline."
    )
    is_success: bool = Field(
        default=True, description="Whether detection completed without fatal error."
    )
